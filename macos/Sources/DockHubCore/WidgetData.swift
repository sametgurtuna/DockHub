/// Son cevaplar: milisaniye ya da kayip paket (nil). Windows karsiligi: Services/PingService.cs -> PingStats.
public struct PingStats: Sendable {
    public static let window = 30
    public private(set) var samples: [Double?] = []

    public init() {}

    public mutating func add(_ milliseconds: Double?) {
        samples.append(milliseconds)
        if samples.count > Self.window { samples.removeFirst(samples.count - Self.window) }
    }

    private var replies: [Double] { samples.compactMap { $0 } }
    public var latest: Double? { samples.last ?? nil }
    public var lastLost: Bool { !samples.isEmpty && samples.last! == nil }
    public var average: Double? { replies.isEmpty ? nil : replies.reduce(0, +) / Double(replies.count) }
    public var min: Double? { replies.min() }
    public var max: Double? { replies.max() }
    /// Kayip paketler, orneklerin yuzdesi.
    public var loss: Double { samples.isEmpty ? 0 : Double(samples.filter { $0 == nil }.count) * 100 / Double(samples.count) }
    /// Cizgi icin: kayip paket en yavas cevap gibi.
    public var history: [Double] { samples.map { $0 ?? (max ?? 0) } }

    /// 60 ms alti iyi, 150 ms alti orta, ustu kotu (Windows: BrushFor).
    public enum Quality: Sendable { case good, fair, poor }
    public static func quality(_ milliseconds: Double?) -> Quality {
        guard let ms = milliseconds else { return .poor }
        return ms < 60 ? .good : (ms < 150 ? .fair : .poor)
    }

    /// `/sbin/ping -c 1` ciktisindan sure: "... time=12.345 ms"; kayipta nil.
    public static func parse(_ output: String) -> Double? {
        guard let range = output.range(of: "time=") else { return nil }
        let rest = output[range.upperBound...]
        let number = rest.prefix { $0.isNumber || $0 == "." }
        return Double(number)
    }

    /// Hedef: bos ya da gecersizse 1.1.1.1. Komut satirina gecmeden once yalniz ad/adres karakterleri.
    public static let defaultTarget = "1.1.1.1"
    public static func target(_ setting: String?) -> String {
        let t = setting?.trimmingCharacters(in: .whitespaces) ?? ""
        guard !t.isEmpty, t.count <= 253, !t.hasPrefix("-"),
              t.allSatisfy({ ($0.isASCII && ($0.isLetter || $0.isNumber)) || ".-:".contains($0) }) else { return defaultTarget }
        return t
    }
}

