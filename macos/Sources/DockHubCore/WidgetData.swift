/// Kopyalanan bir sey: metin ya da gorsel (PNG verisi).
public struct ClipboardEntry: Sendable, Equatable, Identifiable {
    public let id: UUID
    public let text: String?
    public let image: Data?
    public var pinned: Bool
    public let copiedAt: Date

    public init(text: String? = nil, image: Data? = nil, pinned: Bool = false, copiedAt: Date = Date()) {
        self.id = UUID()
        self.text = text
        self.image = image
        self.pinned = pinned
        self.copiedAt = copiedAt
    }
}

/// Son kopyalananlar, yalniz bellekte. Windows karsiligi: Services/ClipboardHistoryService.cs.
/// En fazla 25; sabitlenenler basta durur ve hic dusmez; ayni metin tekrar kopyalaninca one gelir.
public struct ClipboardHistory: Sendable {
    public static let capacity = 25
    public private(set) var entries: [ClipboardEntry] = []

    public init() {}

    /// Parola yoneticilerinin isaretledigi (gizli ya da gecici) veriler hic kaydedilmez
    /// (nspasteboard.org sozlesmesi; 1Password, Bitwarden, KeePassXC kullanir).
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ]

    public static func shouldRecord(types: [String]) -> Bool {
        !types.contains { ignoredTypes.contains($0) }
    }

    public mutating func add(_ entry: ClipboardEntry) {
        if let text = entry.text {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }
            if let i = entries.firstIndex(where: { $0.text == text }) {
                // Ayni metin: one alinir, sabitlemesi korunur.
                let pinned = entries[i].pinned
                entries.remove(at: i)
                insert(ClipboardEntry(text: text, pinned: pinned))
                return
            }
        } else if entry.image == nil {
            return
        } else if let data = entry.image, entries.first(where: { !$0.pinned })?.image == data {
            return
        }
        insert(entry)
    }

    private mutating func insert(_ entry: ClipboardEntry) {
        let firstUnpinned = entries.firstIndex { !$0.pinned } ?? entries.count
        entries.insert(entry, at: entry.pinned ? 0 : firstUnpinned)
        // Kapasite asilirsa en eski sabitlenmemis dusurulur.
        while entries.count > Self.capacity, let last = entries.lastIndex(where: { !$0.pinned }) {
            entries.remove(at: last)
        }
    }

    public mutating func togglePin(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        var entry = entries.remove(at: i)
        entry.pinned.toggle()
        let firstUnpinned = entries.firstIndex { !$0.pinned } ?? entries.count
        entries.insert(entry, at: entry.pinned ? 0 : firstUnpinned)
    }

    public mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }

    /// Sabitlenenler kalir.
    public mutating func clear() { entries.removeAll { !$0.pinned } }
}

