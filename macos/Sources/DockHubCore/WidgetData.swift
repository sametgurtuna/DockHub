/// Windows karsiligi: Services/StockService.cs -> StockQuote.
public struct StockQuote: Sendable, Equatable {
    public let symbol: String
    public let close: Double
    public let previousClose: Double?
    public let history: [Double]
    public let date: Date

    public var changePercent: Double? {
        guard let previousClose, previousClose != 0 else { return nil }
        return (close - previousClose) / previousClose * 100
    }
}

public enum StockData {
    /// "AAPL, MSFT; ^spx" -> sirali ve tekrarsiz semboller.
    public static func splitSymbols(_ text: String) -> [String] {
        var seen = Set<String>()
        return text.split(whereSeparator: { $0 == "," || $0 == ";" || $0 == " " })
            .map { $0.trimmingCharacters(in: .whitespaces).uppercased() }
            .filter { stooqSymbol($0) != nil && seen.insert($0).inserted }
    }

    /// Stooq'taki adi ("AAPL" -> "aapl.us"); sembol olmayan metin icin nil.
    public static func stooqSymbol(_ symbol: String) -> String? {
        let s = symbol.trimmingCharacters(in: .whitespaces).lowercased()
        guard (1...20).contains(s.count),
              s.allSatisfy({ ($0.isASCII && ($0.isLetter || $0.isNumber)) || ".^-_".contains($0) }) else { return nil }
        return s.hasPrefix("^") || s.contains(".") ? s : s + ".us"
    }

    public static func url(for symbol: String, today: Date = Date()) -> URL? {
        guard let stooq = stooqSymbol(symbol) else { return nil }
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyyMMdd"
        let start = today.addingTimeInterval(-30 * 86_400)
        var c = URLComponents(string: "https://stooq.com/q/d/l/")!
        c.queryItems = [URLQueryItem(name: "s", value: stooq), URLQueryItem(name: "i", value: "d"),
                        URLQueryItem(name: "d1", value: f.string(from: start)), URLQueryItem(name: "d2", value: f.string(from: today))]
        return c.url
    }

    /// Stooq gunluk CSV'si ("Date,Open,High,Low,Close,Volume"); "No data" ya da fiyatsiz cevap icin nil.
    public static func parse(_ symbol: String, csv: String) -> StockQuote? {
        let lines = csv.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        guard lines.count >= 2 else { return nil }
        let header = lines[0].split(separator: ",").map { $0.lowercased() }
        guard let dateColumn = header.firstIndex(of: "date"), let closeColumn = header.firstIndex(of: "close") else { return nil }
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.timeZone = TimeZone(identifier: "UTC")
        f.dateFormat = "yyyy-MM-dd"
        var days: [(Date, Double)] = []
        for line in lines.dropFirst() {
            let fields = line.split(separator: ",", omittingEmptySubsequences: false).map(String.init)
            guard fields.count > max(dateColumn, closeColumn), let date = f.date(from: fields[dateColumn]),
                  let close = Double(fields[closeColumn]), close > 0 else { continue }
            days.append((date, close))
        }
        guard !days.isEmpty else { return nil }
        days.sort { $0.0 < $1.0 }
        let latest = days[days.count - 1]
        return StockQuote(symbol: symbol.uppercased(), close: latest.1, previousClose: days.count > 1 ? days[days.count - 2].1 : nil,
                          history: days.map(\.1), date: latest.0)
    }
}

