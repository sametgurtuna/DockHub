/// Yerel liste dosyasi, Windows'taki LocalData ile ayni bicim: {"items": [{"id", "text", "createdAt"}]}.
public struct LocalTodoList: Codable, Sendable {
    public struct Item: Codable, Sendable, Equatable {
        public var id: String
        public var text: String
        public var createdAt: String

        public init(text: String, now: Date = Date()) {
            self.id = UUID().uuidString.replacingOccurrences(of: "-", with: "").lowercased()
            self.text = text
            self.createdAt = ISO8601DateFormatter().string(from: now)
        }
    }

    public var items: [Item] = []

    public init() {}

    public init(from decoder: Decoder) throws {
        var r = try JSONObjectReader(decoder)
        items = r("items", [])
    }
}

extension LocalTodoList.Item {
    public init(from decoder: Decoder) throws {
        var r = try JSONObjectReader(decoder)
        id = r("id", UUID().uuidString.lowercased())
        text = r("text", "")
        createdAt = r("createdAt", "")
    }
}

/// Todoist API v1 (Windows karsiligi: Services/TodoistClient.cs).
public enum TodoistData {
    public static let baseURL = "https://api.todoist.com/api/v1/"

    /// {"results": [{"id","content","checked","due":{"date","datetime"}}], "next_cursor": ...}
    public static func page(_ json: Data) -> (tasks: [TodoTask], cursor: String?) {
        guard let root = try? JSONSerialization.jsonObject(with: json) as? [String: Any] else { return ([], nil) }
        let results = root["results"] as? [[String: Any]] ?? []
        let tasks: [TodoTask] = results.compactMap { t in
            guard (t["checked"] as? Bool) != true else { return nil }
            let id = (t["id"] as? String) ?? (t["id"] as? NSNumber)?.stringValue ?? ""
            let due = t["due"] as? [String: Any]
            return TodoTask(id: id, text: t["content"] as? String ?? "",
                            due: parseDue((due?["datetime"] as? String) ?? (due?["date"] as? String)))
        }
        let cursor = root["next_cursor"] as? String
        return (tasks, cursor?.isEmpty == false ? cursor : nil)
    }

    /// "2026-09-26" (tum gun, yerel gun basi) ya da "2026-09-26T15:00:00" / "...Z".
    public static func parseDue(_ text: String?) -> Date? {
        guard let text, !text.isEmpty else { return nil }
        if text.count == 10 {
            let f = DateFormatter()
            f.locale = Locale(identifier: "en_US_POSIX")
            f.dateFormat = "yyyy-MM-dd"
            return f.date(from: text)
        }
        let iso = ISO8601DateFormatter()
        if let d = iso.date(from: text) { return d }
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd'T'HH:mm:ss"
        return f.date(from: text)
    }

    /// Tarihi olmayanlar en sonda.
    public static func sorted(_ tasks: [TodoTask]) -> [TodoTask] {
        tasks.sorted { ($0.due ?? .distantFuture) < ($1.due ?? .distantFuture) }
    }
}

