public struct StackFile: Sendable, Equatable {
    public let url: URL
    public let name: String
    public let modified: Date
    public let isDirectory: Bool

    public init(url: URL, name: String, modified: Date, isDirectory: Bool) {
        self.url = url
        self.name = name
        self.modified = modified
        self.isDirectory = isDirectory
    }
}

public enum FolderStack {
    /// "date": yeniden eskiye (Windows varsayilani), "name": ada gore.
    public static func sorted(_ files: [StackFile], by sort: String, limit: Int = 30) -> [StackFile] {
        let visible = files.filter { !$0.name.hasPrefix(".") }
        let ordered = sort == "name"
            ? visible.sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
            : visible.sorted { $0.modified > $1.modified }
        return Array(ordered.prefix(limit))
    }
}
