/// Windows karsiligi: Services/CurrencyService.cs -> CurrencyQuote.
public struct CurrencyQuote: Sendable, Equatable {
    public let base: String
    public let target: String
    public let rate: Double
    public let previous: Double?
    public let history: [Double]
    public let isCrypto: Bool

    public var changePercent: Double? {
        guard let previous, previous != 0 else { return nil }
        return (rate - previous) / previous * 100
    }

    /// Kullanicinin yazdigi: para birimi ya da coin.
    public var symbol: String { isCrypto ? base : target }
}

public enum CurrencyData {
    /// Avrupa Merkez Bankasi'nin yayimladiklari (Frankfurter).
    public static let supported: Set<String> = [
        "AUD", "BGN", "BRL", "CAD", "CHF", "CNY", "CZK", "DKK", "EUR", "GBP", "HKD", "HUF", "IDR", "ILS", "INR", "ISK",
        "JPY", "KRW", "MXN", "MYR", "NOK", "NZD", "PHP", "PLN", "RON", "SEK", "SGD", "THB", "TRY", "USD", "ZAR",
    ]

    /// Coin sembolleri ve CoinGecko kimlikleri (Windows'la ayni liste).
    public static let cryptoIds: [String: String] = [
        "BTC": "bitcoin", "ETH": "ethereum", "SOL": "solana", "BNB": "binancecoin", "XRP": "ripple",
        "ADA": "cardano", "DOGE": "dogecoin", "TRX": "tron", "TON": "the-open-network", "DOT": "polkadot",
        "AVAX": "avalanche-2", "LTC": "litecoin", "LINK": "chainlink", "BCH": "bitcoin-cash", "XLM": "stellar",
        "ATOM": "cosmos", "SHIB": "shiba-inu", "USDT": "tether", "USDC": "usd-coin",
    ]

    /// Ayardaki "TRY, EUR; BTC" -> sirali, tekrarsiz, taban haric.
    public static func targets(_ text: String, base: String) -> [String] {
        var seen = Set<String>()
        return text.split(whereSeparator: { $0 == "," || $0 == ";" || $0 == " " })
            .map { $0.trimmingCharacters(in: .whitespaces).uppercased() }
            .filter { !$0.isEmpty && $0 != base.uppercased() && seen.insert($0).inserted }
    }

    public static func frankfurterURL(base: String, targets: [String], today: Date = Date()) -> URL? {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd"
        let start = today.addingTimeInterval(-14 * 86_400)
        return URL(string: "https://api.frankfurter.dev/v1/\(f.string(from: start))..\(f.string(from: today))?from=\(base)&to=\(targets.joined(separator: ","))")
    }

    /// Frankfurter aralik cevabi: {"rates": {"2026-09-29": {"TRY": 41.5}, ...}}; her gecmis eskiden yeniye.
    public static func fiatQuotes(base: String, targets: [String], json: Data) -> [CurrencyQuote] {
        guard let root = try? JSONSerialization.jsonObject(with: json) as? [String: Any],
              let rates = root["rates"] as? [String: [String: Double]] else { return [] }
        let days = rates.keys.sorted()
        return targets.compactMap { target in
            let series = days.compactMap { rates[$0]?[target] }
            guard let latest = series.last else { return nil }
            return CurrencyQuote(base: base, target: target, rate: latest,
                                 previous: series.count > 1 ? series[series.count - 2] : nil,
                                 history: series, isCrypto: false)
        }
    }

    public static func coinGeckoURL(coin: String, currency: String) -> URL? {
        guard let id = cryptoIds[coin.uppercased()] else { return nil }
        return URL(string: "https://api.coingecko.com/api/v3/coins/\(id)/market_chart?vs_currency=\(currency.lowercased())&days=14")
    }

    /// CoinGecko fiyat gecmisi ({"prices": [[ms, fiyat], ...]}): son fiyat, 24 saat onceki ve gunluk son fiyatlar.
    public static func cryptoQuote(coin: String, currency: String, json: Data, calendar: Calendar = .current) -> CurrencyQuote? {
        guard let root = try? JSONSerialization.jsonObject(with: json) as? [String: Any],
              let prices = root["prices"] as? [[Any]] else { return nil }
        let points: [(Date, Double)] = prices.compactMap { pair in
            guard pair.count >= 2, let ms = (pair[0] as? NSNumber)?.doubleValue, let price = (pair[1] as? NSNumber)?.doubleValue
            else { return nil }
            return (Date(timeIntervalSince1970: ms / 1000), price)
        }.sorted { $0.0 < $1.0 }
        guard let latest = points.last else { return nil }
        let dayBefore = latest.0.addingTimeInterval(-86_400)
        let previous = points.last { $0.0 <= dayBefore }?.1
        var daily: [Double] = []
        var lastDay: Date?
        for point in points {
            let day = calendar.startOfDay(for: point.0)
            if day == lastDay { daily[daily.count - 1] = point.1 } else { daily.append(point.1); lastDay = day }
        }
        return CurrencyQuote(base: coin.uppercased(), target: currency.uppercased(), rate: latest.1,
                             previous: previous, history: daily, isCrypto: true)
    }
}

